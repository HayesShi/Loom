def _jsonable(value: Any) -> Any:
    if isinstance(value, dict):
        return {str(key): _jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_jsonable(item) for item in value]
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, np.generic):
        return _jsonable(value.item())
    if isinstance(value, torch.Tensor):
        return _jsonable(value.detach().cpu().tolist())
    if isinstance(value, float) and not math.isfinite(value):
        return None
    return value


def _atomic_json(payload: dict[str, Any], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(f".{path.name}.tmp-{os.getpid()}-{time.time_ns()}")
    try:
        temp.write_text(json.dumps(_jsonable(payload), indent=2, sort_keys=True)
                        + "\n", encoding="utf-8")
        _replace_checkpoint_file(temp, path)
    finally:
        if temp.exists():
            temp.unlink()


def _replace_checkpoint_file(temp: Path, path: Path) -> None:
    # A brief Windows reader handle can reject an otherwise valid atomic
    # replacement. Retry the same complete temporary file before failing.
    for attempt in range(5):
        try:
            os.replace(temp, path)
            return
        except PermissionError:
            if attempt == 4:
                raise
            time.sleep(0.05 * 2 ** attempt)


def _atomic_save(payload: Any, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(f".{path.name}.tmp-{os.getpid()}-{time.time_ns()}")
    try:
        torch.save(payload, temp)
        _replace_checkpoint_file(temp, path)
    finally:
        if temp.exists():
            temp.unlink()


def _append_jsonl(payload: dict[str, Any], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(_jsonable(payload), sort_keys=True) + "\n")
        handle.flush()


def _state_cpu(model: nn.Module) -> dict[str, torch.Tensor]:
    return {name: value.detach().cpu().clone()
            for name, value in model.state_dict().items()}


def _parameter_digest(model: nn.Module) -> str:
    digest = hashlib.sha256()
    for name, parameter in model.named_parameters():
        digest.update(name.encode("utf-8"))
        digest.update(parameter.detach().cpu().contiguous().numpy().tobytes())
    return digest.hexdigest()


def _file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _rng_state(generator: torch.Generator) -> dict[str, Any]:
    return {
        "python": random.getstate(),
        "numpy": np.random.get_state(),
        "torch": torch.get_rng_state(),
        "cuda": (torch.cuda.get_rng_state_all() if torch.cuda.is_available()
                 else None),
        "shuffle": generator.get_state(),
    }


def _restore_rng(state: dict[str, Any], generator: torch.Generator) -> None:
    random.setstate(state["python"])
    np.random.set_state(state["numpy"])
    torch.set_rng_state(state["torch"])
    if state["cuda"] is not None and torch.cuda.is_available():
        torch.cuda.set_rng_state_all(state["cuda"])
    generator.set_state(state["shuffle"])


def _split_id(value: Any) -> int:
    if isinstance(value, str) and value.startswith("Sim"):
        value = value[3:]
    if isinstance(value, bool):
        raise ValueError("Boolean simulation IDs are invalid")
    return int(value)


def _normalizer_from_metadata(metadata: dict[str, Any]) -> tuple[torch.Tensor, torch.Tensor, str]:
    """Find the train-only six-state t=0 moments in preparation metadata."""
    groups = [metadata.get("stats", {}), metadata.get("train_stats", {}),
              metadata.get("normalization", {}), metadata]
    for group_name, group in enumerate(groups):
        if not isinstance(group, dict):
            continue
        for mean_key, std_key in (("input_u_mean", "input_u_std"),
                                  ("u0_mean", "u0_std"),
                                  ("input_mean", "input_std"),
                                  ("x_mean", "x_std")):
            if mean_key not in group or std_key not in group:
                continue
            mean = torch.as_tensor(group[mean_key], dtype=torch.float32).flatten()
            std = torch.as_tensor(group[std_key], dtype=torch.float32).flatten()
            if mean.numel() not in (6, 12) or std.numel() != mean.numel():
                raise ValueError(f"{mean_key}/{std_key} must have 6 or 12 entries")
            mean, std = mean[:6].clone(), std[:6].clone()
            if not torch.isfinite(mean).all() or not torch.isfinite(std).all():
                raise ValueError("Input normalization has nonfinite moments")
            if bool((std < 0).any()):
                raise ValueError("Input standard deviations cannot be negative")
            # The t=0 displacement is often identically zero; leave its
            # corresponding channel at unit scale instead of dividing by zero.
            std = torch.where(std > 1e-8, std, torch.ones_like(std))
            return mean, std, f"group_{group_name}.{mean_key}/{std_key}"
    raise ValueError("metadata.json needs train-only input_u_mean/input_u_std "
                     "(or u0_mean/u0_std, input_mean/input_std, x_mean/x_std)")


def _validate_graph(graph: Any, path: Path) -> None:
    required = ("x", "pos", "u0", "properties", "edge_index", "edge_attr",
                "y", "node_type", "loss_mask")
    for name in required:
        if getattr(graph, name, None) is None:
            raise ValueError(f"{path}: missing {name}")
    nodes = int(graph.num_nodes)
    if nodes < 1 or graph.x.shape != (nodes, 12) \
            or graph.u0.shape != (nodes, 6) \
            or graph.properties.shape != (nodes, 6) \
            or graph.pos.shape != (nodes, 3) \
            or graph.y.shape != (nodes, 6):
        raise ValueError(f"{path}: invalid six-state or 12-input node dimensions")
    if graph.edge_index.ndim != 2 or graph.edge_index.shape[0] != 2 \
            or graph.edge_attr.shape != (graph.edge_index.shape[1], 9):
        raise ValueError(f"{path}: invalid edge_index or official nine-feature edge_attr")
    if graph.node_type.shape != (nodes,) or graph.loss_mask.shape != (nodes,):
        raise ValueError(f"{path}: invalid node_type or loss_mask")
    if graph.loss_mask.dtype != torch.bool:
        raise ValueError(f"{path}: loss_mask must be boolean")
    if not torch.equal(graph.loss_mask, (graph.node_type == 0) |
                       (graph.node_type == 2)):
        raise ValueError(f"{path}: mask differs from official NORMAL/BOUNDARY rule")
    if not bool((graph.node_type == 1).any()) or not bool(graph.loss_mask.any()):
        raise ValueError(f"{path}: force and scored plate nodes are both required")
    if not torch.allclose(graph.x, torch.cat((graph.u0, graph.properties), 1)):
        raise ValueError(f"{path}: x must be t=0 state plus input-only properties")
    if not torch.allclose(graph.pos, graph.u0[:, :3]):
        raise ValueError(f"{path}: pos must be t=0 geometry")
    if graph.edge_index.numel() and (bool((graph.edge_index < 0).any())
                                   or bool((graph.edge_index >= nodes).any())):
        raise ValueError(f"{path}: out-of-range edge")
    for key in ("x", "pos", "u0", "properties", "edge_attr", "y"):
        if not torch.isfinite(getattr(graph, key)).all():
            raise ValueError(f"{path}: nonfinite {key}")


class PlateDataset(Dataset):
    """Lazy prepared PyG graph loader using official six-property inputs."""

    def __init__(self, root: Path, split: str, ids: tuple[int, ...],
                 coordinate_input: bool = False,
                 layout: str = "graph_components",
                 force_feature_scale: float = 1.0):
        if not math.isfinite(force_feature_scale) or force_feature_scale <= 0:
            raise ValueError("force_feature_scale must be positive and finite")
        self.root = root
        self.split = split
        self.ids = ids
        self.coordinate_input = coordinate_input
        self.layout = layout
        self.force_feature_scale = force_feature_scale
        self.cached_graphs: list[Any] | None = None
        self.paths = [root / split / f"Sim{sim_id:03d}.pt" for sim_id in ids]
        missing = [str(path) for path in self.paths if not path.is_file()]
        if missing:
            raise FileNotFoundError(f"{split}: missing {len(missing)} prepared "
                                    f"graphs; first: {missing[0]}")

    def __len__(self) -> int:
        return len(self.ids)

    def __getitem__(self, index: int):
        path = self.paths[index]
        graph = (self.cached_graphs[index].clone()
                 if self.cached_graphs is not None else
                 torch.load(path, map_location="cpu", weights_only=False))
        if getattr(graph, "directed_edge_weight", None) is None:
            graph.directed_edge_weight = _edge_weights(
                graph.edge_index, graph.num_nodes, "directed_symmetric")
        if (self.layout in ("plate_gray_contact", "plate_gray_nearest",
                            "plate_gray_spaced_contact",
                            "plate_scaffold_components", "plate_binary_contact") and
                getattr(graph, "plate_node_to_wire", None) is None):
            graph.plate_node_to_wire = compile_plate_gray_contact(
                graph, mesh_layout=("scaffold_components" if self.layout ==
                                    "plate_scaffold_components" else
                                    "binary" if self.layout ==
                                    "plate_binary_contact" else
                                    "gray_spaced" if self.layout ==
                                    "plate_gray_spaced_contact" else "gray"),
                force_layout=("nearest" if self.layout == "plate_gray_nearest"
                              else "contact"),
                reuse_reference=self.layout in ("plate_gray_contact", "plate_gray_nearest"))
        # The official environment exposes PROPERTIES to the model; u0 is an
        # output offset, and edge_attr already has the official edge scaling.
        graph.x = graph.properties.clone().float()
        if self.force_feature_scale != 1.0:
            graph.x[:, 3:6].div_(self.force_feature_scale)
        if self.coordinate_input:
            graph.x = torch.cat((graph.x, graph.pos[:, :2].float() / 140.),
                                dim=1)
        return graph


def _load_data(root: Path, coordinate_input: bool = False,
               layout: str = "graph_components", include_test: bool = True,
               force_feature_scale: float = 1.0
               ) -> tuple[dict[str, PlateDataset], dict[str, Any]]:
    root = root.resolve()
    metadata_path = root / "metadata.json"
    if not metadata_path.is_file():
        raise FileNotFoundError(f"Prepared metadata is missing: {metadata_path}")
    metadata_bytes = metadata_path.read_bytes()
    metadata = json.loads(metadata_bytes.decode("utf-8"))
    split_record = metadata.get("splits")
    if not isinstance(split_record, dict):
        raise ValueError("metadata.json must contain a splits mapping")
    for split, expected in SPLIT_IDS.items():
        observed = split_record.get(split)
        if not isinstance(observed, list) or tuple(map(_split_id, observed)) != expected:
            raise ValueError(f"{split}: prepared IDs differ from official fixed split")
    loaded_splits = ("train", "val", "test") if include_test else ("train", "val")
    datasets = {split: PlateDataset(root, split, SPLIT_IDS[split],
                                    coordinate_input, layout,
                                    force_feature_scale)
                for split in loaded_splits}
    max_nodes = 0
    sample_shapes = {}
    for split, dataset in datasets.items():
        # Full inventory above rejects missing trajectories. Validate all
        # initial/final arrays once before training rather than per epoch.
        sizes = []
        cached_graphs = []
        for path in dataset.paths:
            graph = torch.load(path, map_location="cpu", weights_only=False)
            _validate_graph(graph, path)
            graph.directed_edge_weight = _edge_weights(
                graph.edge_index, graph.num_nodes, "directed_symmetric")
            if layout in ("plate_gray_contact", "plate_gray_nearest",
                          "plate_gray_spaced_contact",
                          "plate_scaffold_components", "plate_binary_contact"):
                graph.plate_node_to_wire = compile_plate_gray_contact(
                    graph, mesh_layout=("scaffold_components" if layout ==
                                        "plate_scaffold_components" else
                                        "binary" if layout ==
                                        "plate_binary_contact" else
                                        "gray_spaced" if layout ==
                                        "plate_gray_spaced_contact" else "gray"),
                    force_layout=("nearest" if layout == "plate_gray_nearest"
                                  else "contact"),
                    reuse_reference=layout in ("plate_gray_contact", "plate_gray_nearest"))
            sizes.append(int(graph.num_nodes))
            cached_graphs.append(graph)
        dataset.cached_graphs = cached_graphs
        max_nodes = max(max_nodes, max(sizes))
        sample_shapes[split] = {
            "graphs": len(sizes), "min_nodes": min(sizes), "max_nodes": max(sizes),
            "mean_nodes": statistics.mean(sizes),
        }
    info = {
        "benchmark": "ICLR 2026 IGNS Plate Deformation",
        "official_source_commit": OFFICIAL_COMMIT,
        "prepared_root": str(root),
        "metadata_sha256": hashlib.sha256(metadata_bytes).hexdigest(),
        "split_simulation_ids": {split: [ids[0], ids[-1]]
                                 for split, ids in SPLIT_IDS.items()},
        "split_shapes": sample_shapes,
        "max_nodes": max_nodes,
        "max_stages": max(1, (max_nodes - 1).bit_length()),
        "input_processing": {
            "node_input": ("raw_six_properties_plus_initial_xy_divided_by_140"
                           if coordinate_input else "raw_six_properties_only"),
            "edge_input": "official_nine_features_with_geometry_divided_by_400",
            "initial_state": "residual_offset_only",
        },
        "normalization_gap": (
            "Official IGNS normalizes six-state trajectories with its saved "
            "u_stats, currently accumulated only for the last train trajectory; "
            "GCM predicts a raw residual from u0. Both GCM arms share the "
            "same node inputs; the optional coordinate input directly supplies "
            "initial xy beyond the official PROPERTIES-only node input. "
            "Output, loss, and selection use raw units."
        ),
    }
    if force_feature_scale != 1.0:
        info["input_processing"]["force_feature_scale"] = force_feature_scale
    return datasets, info


def _train_output_scale_stats(dataset: PlateDataset) -> dict[str, Any]:
    """Population moments of scored displacement residuals in the train split."""
    count = 0
    residual_sum = torch.zeros(3, dtype=torch.float64)
    residual_sum_sq = torch.zeros(3, dtype=torch.float64)
    graphs = (dataset.cached_graphs if dataset.cached_graphs is not None else
              (dataset[index] for index in range(len(dataset))))
    for graph in graphs:
        mask = graph.loss_mask
        residual = (graph.y[mask, 3:6].double() -
                    graph.u0[mask, 3:6].double())
        count += residual.shape[0]
        residual_sum += residual.sum(dim=0)
        residual_sum_sq += residual.square().sum(dim=0)
    if count < 1:
        raise ValueError("Training split has no scored displacement residuals")
    mean = residual_sum / count
    std = (residual_sum_sq / count - mean.square()).clamp_min(0).sqrt()
    if not torch.isfinite(mean).all() or not torch.isfinite(std).all():
        raise ValueError("Training displacement residual moments are nonfinite")
    return {
        "source_split": "train",
        "graph_count": len(dataset),
        "scored_node_count": count,
        "mask": "loss_mask (NORMAL/BOUNDARY)",
        "target": "y[:, 3:6] - u0[:, 3:6]",
        "std_estimator": "population (divide by scored_node_count)",
        "mean": mean.tolist(),
        "std": std.tolist(),
    }


def _output_scale_stats(args: argparse.Namespace,
                        datasets: dict[str, PlateDataset]
                        ) -> dict[str, Any] | None:
    mode = getattr(args, "output_scale", "none")
    if mode == "none":
        return None
    if mode != "train_std":
        raise ValueError(f"Unknown Plate output scale: {mode}")
    if args.independent_six_state:
        raise ValueError("train_std requires the three-channel displacement head")
    return _train_output_scale_stats(datasets["train"])


def _make_model(args: argparse.Namespace, info: dict[str, Any],
                seed: int, scale: float) -> MultiGraphGCM:
    # This Plate-only compiler supplies explicit mappings to predict_nodes.
    # The model's internal graph compiler is bypassed, and its J is unchanged.
    internal_layout = ("graph_components" if args.layout in
                       ("plate_gray_contact", "plate_gray_nearest",
                        "plate_gray_spaced_contact",
                        "plate_scaffold_components", "plate_binary_contact")
                       else args.layout)
    model = MultiGraphGCM(
        input_dim=8 if getattr(args, "coordinate_input", False) else 6,
        edge_dim=9,
        output_dim=6 if args.independent_six_state else 3, dim=args.dim,
        heads=args.heads, blocks=args.blocks, max_stages=info["max_stages"],
        mode="original", exchange_scale=scale, dropout=args.dropout,
        angle=args.angle, stage_ff=False, graph_embed=True,
        graph_refresh=True, layout=internal_layout, seed=seed,
        tie_pair_gate=args.tie_pair_gate, relay_padding=args.relay_padding,
        prior_only_angle_scale=getattr(args, "plate_distance_angle_prior", False),
        gate_anchor=getattr(args, "gate_anchor", 0.),
        edge_weight_mode=getattr(args, "edge_weight_mode", "directed_symmetric"),
        interstage_head_shuffle=getattr(args, "interstage_head_shuffle", False),
        shuffle_exempt_heads=getattr(args, "shuffle_exempt_heads", 0),
        reverse_odd_blocks=getattr(args, "reverse_odd_blocks", False),
    )
    if args.balanced_carrier_heads:
        with torch.no_grad():
            for block in model.blocks:
                for switch in block.circuit.switches:
                    switch.base[:args.balanced_carrier_heads] = math.pi / 4
    if getattr(args, "plate_distance_angle_prior", False):
        if args.layout not in ("plate_gray_contact", "plate_gray_nearest"):
            raise ValueError("Plate distance angle prior requires a Gray mesh layout")
        if info["max_stages"] != 10:
            raise ValueError("Plate distance angle prior requires 1024 wires")
        model.register_buffer(
            "plate_pair_angle_scales",
            compile_plate_gray_distance_angle_scales(
                args.heads, args.balanced_carrier_heads),
            persistent=False,
        )
    return model


def _predict_raw(model: MultiGraphGCM, batch,
                 freeze_boundary: bool = True,
                 output_std: torch.Tensor | None = None) -> torch.Tensor:
    wire_ids = getattr(batch, "plate_node_to_wire", None)
    mappings = None
    if wire_ids is not None:
        ptr = getattr(batch, "ptr", None)
        if ptr is None:
            mappings = [wire_ids]
        else:
            offsets = ptr.detach().cpu().tolist()
            mappings = [wire_ids[offsets[i]:offsets[i + 1]]
                        for i in range(len(offsets) - 1)]
    pair_angle_scales = getattr(model, "plate_pair_angle_scales", None)
    delta = model.predict_nodes(batch, mappings=mappings,
                                pair_angle_scales=pair_angle_scales)
    if delta.ndim != 2 or delta.shape[0] != batch.y.shape[0]:
        raise ValueError("Full node-state prediction must cover every node")
    if delta.shape[1] == 3:
        if output_std is not None:
            if output_std.shape != (3,):
                raise ValueError("Plate output std must have three channels")
            delta = delta * output_std.to(device=delta.device, dtype=delta.dtype)
        delta = torch.cat((delta, delta), dim=1)
    elif delta.shape[1] != 6:
        raise ValueError("Plate head must predict three or six state channels")
    elif output_std is not None:
        raise ValueError("Output scaling requires a three-channel Plate head")
    # The environment-defined output mask selects NORMAL nodes. The official
    # PDEMatching.forward currently ignores this mask; disabling the clamp
    # provides an otherwise identical ablation.
    if freeze_boundary:
        delta = delta * (batch.node_type == 0).unsqueeze(-1)
    return batch.u0 + delta


class _MetricAccumulator:
    def __init__(self, distance_bins: bool):
        self.nodes = 0
        self.state_sse = 0.0
        self.batch_state_mse_sum = 0.0
        self.batch_count = 0
        self.disp_sse = 0.0
        self.disp_sae = 0.0
        self.disp_vector_sae = 0.0
        self.disp_sum = 0.0
        self.disp_sum2 = 0.0
        self.bin_nodes = [0] * len(DISTANCE_BINS) if distance_bins else None
        self.bin_sse = [0.0] * len(DISTANCE_BINS) if distance_bins else None
        self.bin_vector_sae = ([0.0] * len(DISTANCE_BINS)
                               if distance_bins else None)

    def update(self, prediction: torch.Tensor, batch) -> None:
        if prediction.shape != batch.y.shape or prediction.shape[1] != 6:
            raise ValueError("Invalid 6D prediction/target shape")
        mask = batch.loss_mask
        delta = prediction.double() - batch.y.double()
        disp_delta = delta[mask, 3:6]
        target_disp = batch.y.double()[mask, 3:6]
        self.nodes += int(mask.sum().item())
        batch_state_sse = float(delta[mask].square().sum().item())
        self.state_sse += batch_state_sse
        self.batch_state_mse_sum += batch_state_sse / int(mask.sum().item())
        self.batch_count += 1
        self.disp_sse += float(disp_delta.square().sum().item())
        self.disp_sae += float(disp_delta.abs().sum().item())
        self.disp_vector_sae += float(torch.linalg.vector_norm(
            disp_delta, dim=1).sum().item())
        self.disp_sum += float(target_disp.sum().item())
        self.disp_sum2 += float(target_disp.square().sum().item())
        if self.bin_nodes is None:
            return
        ptr = batch.ptr.tolist()
        for graph_idx in range(len(ptr) - 1):
            start, end = ptr[graph_idx:graph_idx + 2]
            local_mask = mask[start:end]
            force_nodes = batch.node_type[start:end] == 1
            if not bool(force_nodes.any()):
                raise ValueError("A Plate Deformation graph has no force nodes")
            plate_pos = batch.pos[start:end][local_mask].double()
            force_pos = batch.pos[start:end][force_nodes].double()
            distances = torch.cdist(plate_pos, force_pos).amin(dim=1)
            local_delta = delta[start:end, 3:6][local_mask]
            vector_abs = torch.linalg.vector_norm(local_delta, dim=1)
            for i, (lo, hi) in enumerate(DISTANCE_BINS):
                selected = distances >= lo
                if not math.isinf(hi):
                    selected &= distances < hi
                self.bin_nodes[i] += int(selected.sum().item())
                self.bin_sse[i] += float(local_delta[selected].square().sum().item())
                self.bin_vector_sae[i] += float(vector_abs[selected].sum().item())

    def result(self) -> dict[str, Any]:
        if self.nodes < 1:
            raise ValueError("No NORMAL/BOUNDARY plate nodes were scored")
        count = 3 * self.nodes
        denominator = self.disp_sum2 - self.disp_sum ** 2 / count
        result: dict[str, Any] = {
            "state_MSE": self.batch_state_mse_sum / self.batch_count,
            "state_MSE_node_weighted": self.state_sse / self.nodes,
            "displacement_MSE": self.disp_sse / count,
            "displacement_MAE": self.disp_sae / count,
            "displacement_vector_MAE": self.disp_vector_sae / self.nodes,
            "displacement_R2": (1.0 - self.disp_sse / denominator
                                if denominator > 0 else None),
            "scored_nodes": self.nodes,
        }
        if self.bin_nodes is not None:
            result["force_distance_bins"] = {
                f"{lo:g}-{hi:g}" if not math.isinf(hi) else f"{lo:g}-inf": {
                    "nodes": nodes,
                    "displacement_MSE": (self.bin_sse[i] / (3 * nodes)
                                         if nodes else None),
                    "displacement_vector_MAE": (
                        self.bin_vector_sae[i] / nodes if nodes else None),
                }
                for i, ((lo, hi), nodes) in enumerate(zip(
                    DISTANCE_BINS, self.bin_nodes))
            }
        return result


@torch.no_grad()
def _evaluate(model: MultiGraphGCM, loader: DataLoader,
              device: torch.device, distance_bins: bool,
              freeze_boundary: bool = True,
              output_std: torch.Tensor | None = None) -> dict[str, Any]:
    model.eval()
    metrics = _MetricAccumulator(distance_bins)
    for batch in loader:
        batch = batch.to(device)
        prediction = _predict_raw(model, batch, freeze_boundary, output_std)
        if not torch.isfinite(prediction).all():
            raise FloatingPointError("Nonfinite Plate Deformation prediction")
        metrics.update(prediction, batch)
    return metrics.result()


def _train_epoch(model: MultiGraphGCM, loader: DataLoader,
                 optimizer: torch.optim.Optimizer, device: torch.device,
                 clip_norm: float, freeze_boundary: bool = True,
                 output_std: torch.Tensor | None = None) -> float:
    model.train()
    state_sse = 0.0
    scored_nodes = 0
    for batch in loader:
        batch = batch.to(device)
        optimizer.zero_grad(set_to_none=True)
        prediction = _predict_raw(model, batch, freeze_boundary, output_std)
        delta = prediction[batch.loss_mask] - batch.y[batch.loss_mask]
        loss = delta.square().sum(dim=1).mean()
        if not torch.isfinite(loss):
            raise FloatingPointError("Nonfinite raw Plate Deformation loss")
        loss.backward()
        nn.utils.clip_grad_norm_(model.parameters(), clip_norm)
        optimizer.step()
        nodes = int(batch.loss_mask.sum().item())
        state_sse += float(loss.detach().item()) * nodes
        scored_nodes += nodes
    return state_sse / scored_nodes


def _config(args: argparse.Namespace, info: dict[str, Any], seed: int,
            scale: float,
            output_scale_stats: dict[str, Any] | None = None,
            warm_start: dict[str, Any] | None = None) -> dict[str, Any]:
    mode = getattr(args, "output_scale", "none")
    if (mode == "train_std") != (output_scale_stats is not None):
        raise ValueError("train_std config requires training output scale statistics")
    if mode not in ("none", "train_std"):
        raise ValueError(f"Unknown Plate output scale: {mode}")
    config = {
        "runner": "run_plate_deformation", "benchmark": info["benchmark"],
        "official_source_commit": OFFICIAL_COMMIT,
        "metadata_sha256": info["metadata_sha256"],
        "prepared_root": info["prepared_root"],
        "fixed_splits": info["split_simulation_ids"],
        "input_timestep": 0, "target_timestep": 47,
        "input_processing": info["input_processing"],
        "normalization_gap": info["normalization_gap"],
        "seed": seed,
        "model": {
            "class": "MultiGraphGCM",
            "input_dim": 8 if getattr(args, "coordinate_input", False) else 6,
            "edge_dim": 9,
            "coordinate_input": getattr(args, "coordinate_input", False),
            "coordinate_input_scale": 140. if getattr(args, "coordinate_input", False) else None,
            "output_dim": 6 if args.independent_six_state else 3,
            "output_rule": ("u0 + six-state delta"
                            if args.independent_six_state else
                            "u0 + [displacement, displacement]"),
            "freeze_boundary": args.freeze_boundary,
            "dim": args.dim, "heads": args.heads, "blocks": args.blocks,
            "max_stages": info["max_stages"], "layout": args.layout,
            "mode": "original", "exchange_scale": scale,
            "relay_padding": args.relay_padding, "dropout": args.dropout,
            "angle": args.angle, "stage_ff": False, "graph_embed": True,
            "graph_refresh": True, "tie_pair_gate": args.tie_pair_gate,
            "edge_weight_mode": getattr(args, "edge_weight_mode", "directed_symmetric"),
            "balanced_carrier_heads": args.balanced_carrier_heads,
            "balanced_carrier_initial_angle": (
                math.pi / 4 if args.balanced_carrier_heads else None),
        },
        "training": {
            "loss": "raw six-channel sum-of-squares per NORMAL/BOUNDARY node",
            "selection": "minimum validation batch-mean raw state_MSE",
            "optimizer": "AdamW", "lr": args.lr,
            "weight_decay": args.weight_decay, "batch_size": args.batch_size,
            "epochs": args.epochs, "patience": args.patience,
            "clip_norm": args.clip_norm, "num_workers": 0,
            "shuffle_seed": seed + 104729,
        },
    }
    if getattr(args, "interstage_head_shuffle", False):
        config["model"]["interstage_head_shuffle"] = "complete_real_imag_pair"
    if getattr(args, "shuffle_exempt_heads", 0):
        config["model"]["shuffle_exempt_heads"] = int(args.shuffle_exempt_heads)
    if getattr(args, "reverse_odd_blocks", False):
        config["model"]["reverse_odd_blocks"] = True
    if getattr(args, "gate_anchor", 0.) > 0.:
        config["model"]["gate_anchor"] = float(args.gate_anchor)
    if getattr(args, "force_feature_scale", 1.0) != 1.0:
        config["model"]["force_feature_scale"] = float(args.force_feature_scale)
    if getattr(args, "plate_distance_angle_prior", False):
        config["model"]["plate_distance_angle_prior"] = True
        config["model"]["prior_only_angle_scale"] = True
    if output_scale_stats is not None:
        config["model"]["output_scale"] = {
            "mode": "train_std", "training_stats": output_scale_stats,
        }
    if warm_start is not None:
        config["warm_start"] = warm_start
        config["training"]["optimizer_initialization"] = "fresh_state"
    return config


def _warm_start_source(args: argparse.Namespace, info: dict[str, Any],
                       seed: int, scale: float,
                       output_scale_stats: dict[str, Any] | None
                       ) -> dict[str, Any] | None:
    source_root = getattr(args, "warm_start_from", None)
    if source_root is None:
        return None
    source_root = Path(source_root).resolve()
    output_root = args.output.resolve()
    if (source_root == output_root or source_root in output_root.parents
            or output_root in source_root.parents):
        raise ValueError("Warm-start source and new output must be separate directories")
    source_folder = source_root / f"seed_{seed}" / f"scale_{_scale_tag(scale)}"
    validation_path = source_folder / "validation_only.json"
    if not validation_path.is_file():
        validation_path = source_folder / "result.json"
    if not validation_path.is_file():
        raise FileNotFoundError(
            f"Warm start requires a completed validation-selected arm: {source_folder}")
    record = json.loads(validation_path.read_text(encoding="utf-8"))
    if record.get("status") not in ("validated_no_test", "completed"):
        raise ValueError(f"Warm-start source has no completed validation: {validation_path}")
    if validation_path.name == "result.json" and record["status"] != "completed":
        raise ValueError(f"Warm-start result is incomplete: {validation_path}")
    base = _config(args, info, seed, scale, output_scale_stats)
    source_config = record.get("config")
    if not isinstance(source_config, dict):
        raise ValueError(f"Warm-start source has no config: {validation_path}")
    source_without_training = {key: value for key, value in source_config.items()
                               if key != "training"}
    base_without_training = {key: value for key, value in base.items()
                             if key != "training"}
    if source_without_training != base_without_training:
        raise ValueError("Warm-start source changes model, J, input, or dataset config")
    source_training = dict(source_config.get("training", {}))
    target_training = dict(base["training"])
    source_lr = source_training.get("lr")
    if (not isinstance(source_lr, (int, float)) or
            not math.isfinite(source_lr) or not 0 < args.lr < source_lr):
        raise ValueError("Warm-start learning rate must be finite and below source LR")
    for setting in ("lr", "epochs", "patience"):
        source_training.pop(setting, None)
        target_training.pop(setting, None)
    if source_training != target_training:
        raise ValueError("Warm start may change only LR, epochs, and patience")
    best_path = source_folder / "best.pt"
    if Path(record.get("best_checkpoint", "")).resolve() != best_path.resolve():
        raise ValueError(f"Warm-start record points to a different best.pt: {validation_path}")
    if not best_path.is_file():
        raise FileNotFoundError(f"Warm-start best checkpoint missing: {best_path}")
    selected_epoch = int(record.get("selected_epoch", -1))
    val = record.get("val", {})
    if selected_epoch < 1 or not isinstance(val, dict) or not math.isfinite(
            float(val.get("state_MSE", math.nan))):
        raise ValueError(f"Warm-start source lacks a validation-selected epoch: {validation_path}")
    return {
        "source_record": str(validation_path.resolve()),
        "source_record_sha256": _file_sha256(validation_path),
        "source_checkpoint": str(best_path.resolve()),
        "source_checkpoint_sha256": _file_sha256(best_path),
        "source_selected_epoch": selected_epoch,
        "source_val_state_MSE": float(val["state_MSE"]),
        "source_lr": float(source_lr),
        "target_lr": float(args.lr),
    }


def _load_warm_start_state(warm_start: dict[str, Any]
                           ) -> tuple[dict[str, torch.Tensor], dict[str, Any]]:
    record_path = Path(warm_start["source_record"])
    best_path = Path(warm_start["source_checkpoint"])
    if (_file_sha256(record_path) != warm_start["source_record_sha256"] or
            _file_sha256(best_path) != warm_start["source_checkpoint_sha256"]):
        raise ValueError("Warm-start source changed after validation record was checked")
    record = json.loads(record_path.read_text(encoding="utf-8"))
    selected = torch.load(best_path, map_location="cpu", weights_only=False)
    if (_file_sha256(best_path) != warm_start["source_checkpoint_sha256"] or
            selected.get("config") != record.get("config") or
            int(selected.get("epoch", -1)) != warm_start["source_selected_epoch"] or
            _jsonable(selected.get("val")) != record.get("val")):
        raise ValueError("Warm-start best.pt differs from its validation-selected record")
    return selected["model"], selected["val"]


def _run_arm(args: argparse.Namespace, datasets: dict[str, PlateDataset],
             info: dict[str, Any], seed: int, scale: float,
             device: torch.device,
             output_scale_stats: dict[str, Any] | None = None,
             defer_test: bool = False) -> dict[str, Any]:
    if getattr(args, "output_scale", "none") == "train_std":
        if args.independent_six_state:
            raise ValueError("train_std requires the three-channel displacement head")
        if output_scale_stats is None:
            output_scale_stats = _output_scale_stats(args, datasets)
        output_std = torch.as_tensor(output_scale_stats["std"], device=device,
                                     dtype=torch.float32)
    elif getattr(args, "output_scale", "none") == "none":
        if output_scale_stats is not None:
            raise ValueError("Output scale statistics require train_std mode")
        output_std = None
    else:
        raise ValueError(f"Unknown Plate output scale: {args.output_scale}")
    tag = _scale_tag(scale)
    folder = args.output / f"seed_{seed}" / f"scale_{tag}"
    result_path = folder / "result.json"
    validation_path = folder / "validation_only.json"
    latest_path = folder / "latest.pt"
    best_path = folder / "best.pt"
    trace_path = folder / "epochs.jsonl"
    warm_start = _warm_start_source(args, info, seed, scale,
                                    output_scale_stats)
    config = _config(args, info, seed, scale, output_scale_stats, warm_start)
    if result_path.exists():
        if defer_test:
            raise FileExistsError(
                f"Arm already has a test result; use paired mode: {result_path}")
        if not args.resume:
            raise FileExistsError(f"Result exists; pass --resume: {result_path}")
        result = json.loads(result_path.read_text(encoding="utf-8"))
        if result["config"] != config:
            raise ValueError(f"Cannot reuse incompatible result: {result_path}")
        print(json.dumps({"already_complete": str(result_path)}), flush=True)
        return result
    validated = None
    if validation_path.exists():
        if not args.resume:
            raise FileExistsError(
                f"Validation-only arm exists; pass --resume: {validation_path}")
        validated = json.loads(validation_path.read_text(encoding="utf-8"))
        if validated["config"] != config:
            raise ValueError(
                f"Cannot reuse incompatible validation-only arm: {validation_path}")
        if defer_test:
            print(json.dumps({"already_validated": str(validation_path)}),
                  flush=True)
            return validated
        if not latest_path.exists() or not best_path.exists():
            raise FileNotFoundError(
                f"Validation-only arm needs best and latest checkpoints: {folder}")
    if latest_path.exists() and not args.resume:
        raise FileExistsError(f"Checkpoint exists; pass --resume: {latest_path}")
    if warm_start is not None and best_path.exists() and not latest_path.exists():
        raise RuntimeError(f"Warm-start target has best.pt but no latest.pt: {folder}")

    _seed_everything(seed)
    _sync(device)
    init_started = time.perf_counter()
    model = _make_model(args, info, seed, scale).to(device)
    _sync(device)
    init_seconds = time.perf_counter() - init_started
    initial_digest = _parameter_digest(model)
    if (validated is not None and
            validated["initial_parameter_digest"] != initial_digest):
        raise ValueError(
            f"Validation-only arm has incompatible initialization: {validation_path}")
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr,
                                  weight_decay=args.weight_decay)
    generator = torch.Generator().manual_seed(seed + 104729)
    loaders = {
        split: DataLoader(dataset, batch_size=args.batch_size,
                          shuffle=(split == "train"), num_workers=0,
                          generator=(generator if split == "train" else None))
        for split, dataset in datasets.items()
    }
    start_epoch = 1
    best_epoch = 0
    best_val = math.inf
    patience_count = 0
    elapsed_before = 0.0
    start_parameter_digest = initial_digest
    if warm_start is not None and not latest_path.exists():
        state, source_val = _load_warm_start_state(warm_start)
        model.load_state_dict(state, strict=True)
        start_parameter_digest = _parameter_digest(model)
        best_val = float(source_val["state_MSE"])
        _atomic_save({"config": config, "epoch": 0,
                      "val": source_val, "model": _state_cpu(model)}, best_path)
        _atomic_save({"config": config,
                      "initial_parameter_digest": initial_digest,
                      "start_parameter_digest": start_parameter_digest,
                      "epoch": 0, "model": _state_cpu(model),
                      "optimizer": optimizer.state_dict(),
                      "rng": _rng_state(generator), "best_epoch": 0,
                      "best_val_state_MSE": best_val,
                      "patience_count": 0, "elapsed_seconds": 0.0}, latest_path)
    if latest_path.exists():
        saved = torch.load(latest_path, map_location="cpu", weights_only=False)
        if saved["config"] != config or saved["initial_parameter_digest"] != initial_digest:
            raise ValueError(f"Cannot resume incompatible checkpoint: {latest_path}")
        start_parameter_digest = saved.get("start_parameter_digest", initial_digest)
        if warm_start is not None and "start_parameter_digest" not in saved:
            raise ValueError(f"Warm-start checkpoint lacks start digest: {latest_path}")
        model.load_state_dict(saved["model"])
        optimizer.load_state_dict(saved["optimizer"])
        _restore_rng(saved["rng"], generator)
        start_epoch = int(saved["epoch"]) + 1
        best_epoch = int(saved["best_epoch"])
        best_val = float(saved["best_val_state_MSE"])
        patience_count = int(saved["patience_count"])
        elapsed_before = float(saved["elapsed_seconds"])

    if device.type == "cuda":
        torch.cuda.reset_peak_memory_stats(device)
    started = time.perf_counter()
    epoch_times: list[float] = []
    final_epoch = (int(validated["epochs_completed"])
                   if validated is not None else start_epoch - 1)
    print(json.dumps({"seed": seed, "exchange_scale": scale,
                      "start_epoch": start_epoch,
                      "parameters": sum(p.numel() for p in model.parameters()),
                      "max_stages": info["max_stages"],
                      "relay_padding": args.relay_padding,
                      "device": str(device)}), flush=True)
    epochs_to_run = (() if validated is not None else
                     range(start_epoch, args.epochs + 1))
    for epoch in epochs_to_run:
        epoch_started = time.perf_counter()
        final_epoch = epoch
        train_loss = _train_epoch(model, loaders["train"], optimizer, device,
                                  args.clip_norm, args.freeze_boundary,
                                  output_std)
        validation = _evaluate(model, loaders["val"], device,
                               distance_bins=False,
                               freeze_boundary=args.freeze_boundary,
                               output_std=output_std)
        if validation["state_MSE"] < best_val - 1e-12:
            best_val = validation["state_MSE"]
            best_epoch = epoch
            patience_count = 0
            _atomic_save({"config": config, "epoch": epoch,
                          "val": validation, "model": _state_cpu(model)},
                         best_path)
        else:
            patience_count += 1
        _sync(device)
        epoch_seconds = time.perf_counter() - epoch_started
        epoch_times.append(epoch_seconds)
        elapsed = elapsed_before + time.perf_counter() - started
        _append_jsonl({"epoch": epoch, "train_state_MSE": train_loss,
                       "val": validation, "best_epoch": best_epoch,
                       "best_val_state_MSE": best_val,
                       "elapsed_seconds": elapsed,
                       "epoch_seconds": epoch_seconds}, trace_path)
        _atomic_save({"config": config,
                      "initial_parameter_digest": initial_digest,
                      "start_parameter_digest": start_parameter_digest,
                      "epoch": epoch, "model": _state_cpu(model),
                      "optimizer": optimizer.state_dict(),
                      "rng": _rng_state(generator),
                      "best_epoch": best_epoch,
                      "best_val_state_MSE": best_val,
                      "patience_count": patience_count,
                      "elapsed_seconds": elapsed}, latest_path)
        if epoch == 1 or epoch % args.print_every == 0 or epoch == args.epochs:
            print(json.dumps({"seed": seed, "exchange_scale": scale,
                              "epoch": epoch, "train_state_MSE": train_loss,
                              "val_state_MSE": validation["state_MSE"],
                              "best_epoch": best_epoch}), flush=True)
        if patience_count >= args.patience:
            break

    if best_epoch < (0 if warm_start is not None else 1) or not best_path.exists():
        raise RuntimeError("No validation-selected checkpoint is available")
    selected = torch.load(best_path, map_location="cpu", weights_only=False)
    if selected["config"] != config:
        raise ValueError(f"Best checkpoint has a different config: {best_path}")
    model.load_state_dict(selected["model"])
    if defer_test:
        _sync(device)
        training_seconds = elapsed_before + time.perf_counter() - started
        validation_only = {
            "status": "validated_no_test", "config": config,
            "dataset_info": info,
            "initial_parameter_digest": initial_digest,
            "start_parameter_digest": start_parameter_digest,
            "parameter_count": sum(p.numel() for p in model.parameters()),
            "selected_epoch": best_epoch, "epochs_completed": final_epoch,
            "val": selected["val"],
            "model_init_seconds": init_seconds,
            "training_seconds": training_seconds,
            "median_epoch_seconds_this_invocation": (
                statistics.median(epoch_times) if epoch_times else None),
            "peak_cuda_allocated_bytes": (
                torch.cuda.max_memory_allocated(device)
                if device.type == "cuda" else None),
            "best_checkpoint": str(best_path.resolve()),
            "trace_path": str(trace_path.resolve()),
            "environment": {
                "python": sys.version, "platform": platform.platform(),
                "torch": torch.__version__, "device": str(device),
                "cuda_device": (torch.cuda.get_device_name(device)
                                if device.type == "cuda" else None),
            },
        }
        if output_scale_stats is not None:
            validation_only["train_output_scale_stats"] = output_scale_stats
        if warm_start is not None:
            validation_only["warm_start"] = warm_start
        _atomic_json(validation_only, validation_path)
        print(json.dumps({"validation_only": str(validation_path),
                          "selected_epoch": best_epoch,
                          "val_state_MSE": selected["val"]["state_MSE"],
                          "training_seconds": training_seconds}), flush=True)
        return validation_only
    # Only a validation-selected model touches the test split.
    if "test" not in loaders:
        raise ValueError("Test split is required to finalize a paired arm")
    test = _evaluate(model, loaders["test"], device, distance_bins=True,
                     freeze_boundary=args.freeze_boundary,
                     output_std=output_std)
    _sync(device)
    training_seconds = elapsed_before + time.perf_counter() - started
    result = {
        "status": "completed", "config": config,
        "dataset_info": info,
        "initial_parameter_digest": initial_digest,
        "start_parameter_digest": start_parameter_digest,
        "parameter_count": sum(p.numel() for p in model.parameters()),
        "selected_epoch": best_epoch, "epochs_completed": final_epoch,
        "val": selected["val"], "test": test,
        "model_init_seconds": init_seconds,
        "training_seconds": training_seconds,
        "median_epoch_seconds_this_invocation": (
            statistics.median(epoch_times) if epoch_times else None),
        "peak_cuda_allocated_bytes": (
            torch.cuda.max_memory_allocated(device)
            if device.type == "cuda" else None),
        "best_checkpoint": str(best_path.resolve()),
        "trace_path": str(trace_path.resolve()),
        "environment": {
            "python": sys.version, "platform": platform.platform(),
            "torch": torch.__version__, "device": str(device),
            "cuda_device": (torch.cuda.get_device_name(device)
                            if device.type == "cuda" else None),
        },
    }
    if output_scale_stats is not None:
        result["train_output_scale_stats"] = output_scale_stats
    if warm_start is not None:
        result["warm_start"] = warm_start
    if validated is not None:
        for key in ("model_init_seconds", "training_seconds",
                    "median_epoch_seconds_this_invocation",
                    "peak_cuda_allocated_bytes", "environment"):
            result[key] = validated[key]
        training_seconds = float(validated["training_seconds"])
    _atomic_json(result, result_path)
    print(json.dumps({"result": str(result_path),
                      "selected_epoch": best_epoch,
                      "val_state_MSE": selected["val"]["state_MSE"],
                      "test_state_MSE": test["state_MSE"],
                      "training_seconds": training_seconds}), flush=True)
    return result


def _check_only(args: argparse.Namespace, datasets: dict[str, PlateDataset],
                info: dict[str, Any],
                output_scale_stats: dict[str, Any] | None = None) -> None:
    """Check two prepared graphs and original-J forward on CPU, without scores."""
    if (getattr(args, "output_scale", "none") == "train_std" and
            output_scale_stats is None):
        output_scale_stats = _output_scale_stats(args, datasets)
    _seed_everything(args.seeds[0])
    batch = next(iter(DataLoader(datasets["train"], batch_size=2,
                                 shuffle=False, num_workers=0)))
    model = _make_model(args, info, args.seeds[0],
                        _paired_scales(args)[1]).cpu().eval()
    output_std = (torch.tensor(output_scale_stats["std"], dtype=torch.float32)
                  if output_scale_stats is not None else None)
    with torch.inference_mode():
        prediction = _predict_raw(model, batch, args.freeze_boundary, output_std)
    if prediction.shape != batch.y.shape or not torch.isfinite(prediction).all():
        raise AssertionError("CPU Plate Deformation forward failed")
    print(json.dumps({"check": "passed", "graphs": 2,
                      "prediction_shape": list(prediction.shape),
                      "max_nodes": info["max_nodes"],
                      "max_stages": info["max_stages"],
                      "relay_padding": args.relay_padding,
                      "note": "No training or benchmark score was run"}),
          flush=True)


def _require_deferred_pair_files_ready(args: argparse.Namespace,
                                       seed: int) -> list[Path] | None:
    """Check deferred-arm completion before opening any test graph files."""
    folders = [args.output / f"seed_{seed}" / f"scale_{_scale_tag(scale)}"
               for scale in _paired_scales(args)]
    if not any((folder / "validation_only.json").exists()
               for folder in folders):
        return None
    if not args.resume:
        raise FileExistsError("Finalizing validation-only arms requires --resume")
    for folder in folders:
        validation_path = folder / "validation_only.json"
        if not validation_path.exists() and not (folder / "result.json").exists():
            raise RuntimeError(
                "Both arms must finish validation before either test is read; "
                f"missing {validation_path}")
    return folders


def _require_deferred_pair_ready(args: argparse.Namespace,
                                 info: dict[str, Any], seed: int,
                                 output_scale_stats: dict[str, Any] | None
                                 ) -> None:
    """Check both deferred configs and checkpoints before either test score."""
    folders = _require_deferred_pair_files_ready(args, seed)
    if folders is None:
        return
    for scale, folder in zip(_paired_scales(args), folders):
        warm_start = _warm_start_source(args, info, seed, scale,
                                        output_scale_stats)
        expected = _config(args, info, seed, scale, output_scale_stats,
                           warm_start)
        result_path = folder / "result.json"
        if result_path.exists():
            completed = json.loads(result_path.read_text(encoding="utf-8"))
            if completed["config"] != expected:
                raise ValueError(f"Cannot reuse incompatible result: {result_path}")
            continue
        validation_path = folder / "validation_only.json"
        validated = json.loads(validation_path.read_text(encoding="utf-8"))
        if validated["config"] != expected:
            raise ValueError(
                f"Cannot finalize incompatible validation-only arm: {validation_path}")
        if not (folder / "best.pt").exists() or not (folder / "latest.pt").exists():
            raise FileNotFoundError(
                f"Validation-only arm needs best and latest checkpoints: {folder}")


def _run_seed(args: argparse.Namespace, datasets: dict[str, PlateDataset],
              info: dict[str, Any], seed: int, device: torch.device,
              output_scale_stats: dict[str, Any] | None = None
              ) -> dict[str, Any]:
    arm = getattr(args, "arm", "paired")
    scales = _paired_scales(args)
    if arm in ("zero", "j"):
        scale = scales[0] if arm == "zero" else scales[1]
        validated = _run_arm(args, datasets, info, seed, scale, device,
                             output_scale_stats, defer_test=True)
        if device.type == "cuda":
            torch.cuda.empty_cache()
        return validated
    if arm != "paired":
        raise ValueError(f"Unknown Plate arm: {arm}")
    _require_deferred_pair_ready(args, info, seed, output_scale_stats)
    zero, exchange = [
        _run_arm(args, datasets, info, seed, scale, device,
                 output_scale_stats)
        for scale in scales
    ]
    if zero["initial_parameter_digest"] != exchange["initial_parameter_digest"]:
        raise RuntimeError("Paired arms did not share initialized parameters")
    paired = {
        "benchmark": info["benchmark"], "seed": seed,
        "initial_parameter_digest": zero["initial_parameter_digest"],
        "relay_padding": args.relay_padding,
        "zero": {"selected_epoch": zero["selected_epoch"],
                 "val": zero["val"], "test": zero["test"]},
        f"exchange_{_scale_tag(scales[1])}": {
            "selected_epoch": exchange["selected_epoch"],
            "val": exchange["val"], "test": exchange["test"]},
        "delta_exchange_minus_zero": {
            split: {
                metric: exchange[split][metric] - zero[split][metric]
                for metric in ("state_MSE", "displacement_MSE",
                               "displacement_MAE", "displacement_R2")
                if exchange[split][metric] is not None
                and zero[split][metric] is not None
            }
            for split in ("val", "test")
        },
    }
    if getattr(args, "warm_start_from", None) is not None:
        paired["warm_start"] = {
            "zero": zero["warm_start"],
            f"exchange_{_scale_tag(scales[1])}": exchange["warm_start"],
        }
        paired["start_parameter_digest"] = {
            "zero": zero["start_parameter_digest"],
            f"exchange_{_scale_tag(scales[1])}":
                exchange["start_parameter_digest"],
        }
    paired_name = ("paired.json" if scales[1] == SCALES[1] else
                   f"paired_scale_{_scale_tag(scales[1])}.json")
    paired_path = args.output / f"seed_{seed}" / paired_name
    _atomic_json(paired, paired_path)
    print(json.dumps({"paired_result": str(paired_path),
                      "delta_test_state_MSE":
                      paired["delta_exchange_minus_zero"]["test"]["state_MSE"]}),
          flush=True)
    if device.type == "cuda":
        torch.cuda.empty_cache()
    return paired


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-root", type=Path,
                        default=data_path('plate_deformation/processed_static'))
    parser.add_argument("--output", type=Path,
                        default=REPO / "results" / "plate_deformation_gcm")
    parser.add_argument("--arm", choices=["paired", "zero", "j"],
                        default="paired",
                        help="Run both arms and compare, or validate one arm without reading test")
    parser.add_argument("--seeds", "--seed", type=int, nargs="+", default=[0])
    parser.add_argument("--batch-size", type=int, default=8)
    parser.add_argument("--epochs", type=int, default=2000)
    parser.add_argument("--patience", type=int, default=200)
    parser.add_argument("--dim", type=int, default=64)
    parser.add_argument("--heads", type=int, default=4)
    parser.add_argument("--blocks", type=int, default=2)
    parser.add_argument("--dropout", type=float, default=0.1)
    parser.add_argument("--angle", type=float, default=0.2)
    parser.add_argument("--j-exchange-scale", type=float, default=0.25,
                        help="Interpolate once between the full original J circuit output and its input")
    parser.add_argument("--gate-anchor", type=float, default=0.,
                        help="Blend each stage's gate input with its circuit-entry state; the J carrier still rotates the current state")
    parser.add_argument("--tie-pair-gate", action="store_true")
    parser.add_argument("--relay-padding", action="store_true")
    parser.add_argument("--balanced-carrier-heads", type=int, default=0,
                        help="Initialize first K existing J heads at pi/4 at all stages")
    parser.add_argument("--independent-six-state", action="store_true",
                        help="Ablation: predict six independent state deltas")
    parser.add_argument("--output-scale", choices=["none", "train_std"],
                        default="none",
                        help="Scale the three-channel head by train-only scored displacement-residual std")
    parser.add_argument("--coordinate-input", action="store_true",
                        help="Append initial plate x,y positions divided by the known 140-unit plate side")
    parser.add_argument("--force-feature-scale", type=float, default=1.0,
                        help="Divide only the three force-vector node properties by this positive scale")
    parser.add_argument("--interstage-head-shuffle", action="store_true",
                        help="Permute complete complex channel pairs between original J stages")
    parser.add_argument("--shuffle-exempt-heads", type=int, default=0,
                        help="Keep the first K existing carrier heads fixed during interstage head shuffling")
    parser.add_argument("--reverse-odd-blocks", action="store_true",
                        help="Run the existing J stages in reverse order in every second block")
    parser.add_argument("--plate-distance-angle-prior", action="store_true",
                        help="Scale existing non-carrier J angles by fixed Gray mesh pair distance")
    parser.add_argument("--freeze-boundary", action=argparse.BooleanOptionalAction,
                        default=True,
                        help="Keep non-NORMAL state at t=0; disable for unclamped ablation")
    parser.add_argument("--layout", choices=["graph_components", "graph",
                                             "input_order", "plate_gray_contact",
                                             "plate_gray_nearest",
                                             "plate_gray_spaced_contact",
                                             "plate_scaffold_components",
                                             "plate_binary_contact"],
                        default="graph_components")
    parser.add_argument("--edge-weight-mode",
                        choices=["directed_symmetric", "target_mean", "symmetric"],
                        default="directed_symmetric",
                        help="Normalize directed force-to-mesh messages without erasing them")
    parser.add_argument("--lr", type=float, default=5e-4)
    parser.add_argument("--warm-start-from", type=Path,
                        help="Completed source output root; initialize each arm from its validation-selected best.pt with a fresh optimizer and lower LR in a separate output")
    parser.add_argument("--weight-decay", type=float, default=1e-5)
    parser.add_argument("--clip-norm", type=float, default=1.0)
    parser.add_argument("--threads", type=int, default=4)
    parser.add_argument("--device", choices=["auto", "cpu", "cuda"],
                        default="auto")
    parser.add_argument("--print-every", type=int, default=10)
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--check-only", action="store_true")
    args = parser.parse_args()
    if args.device == "auto":
        args.device = "cuda" if torch.cuda.is_available() else "cpu"
    if args.device == "cuda" and not torch.cuda.is_available():
        parser.error("CUDA was requested but is unavailable")
    if (args.batch_size < 1 or args.epochs < 1 or args.patience < 1
            or args.blocks < 1 or args.threads < 1 or args.print_every < 1
            or args.lr <= 0 or args.clip_norm <= 0 or args.weight_decay < 0):
        parser.error("Invalid positive training setting")
    if args.dim < 1 or args.heads < 1 or args.dim % (2 * args.heads):
        parser.error("dim must be divisible by twice the head count")
    if not 0 <= args.balanced_carrier_heads <= args.heads:
        parser.error("balanced-carrier-heads must be between zero and heads")
    if not 0 <= args.shuffle_exempt_heads < args.heads:
        parser.error("shuffle-exempt-heads must be in [0, heads)")
    if args.shuffle_exempt_heads and not args.interstage_head_shuffle:
        parser.error("shuffle-exempt-heads requires interstage-head-shuffle")
    if args.shuffle_exempt_heads > args.balanced_carrier_heads:
        parser.error("shuffle-exempt-heads cannot exceed balanced-carrier-heads")
    if (args.plate_distance_angle_prior and args.layout not in
            ("plate_gray_contact", "plate_gray_nearest")):
        parser.error("plate-distance-angle-prior requires a Gray mesh layout")
    if args.output_scale == "train_std" and args.independent_six_state:
        parser.error("train_std requires the three-channel displacement head")
    if not 0 <= args.dropout < 1 or not math.isfinite(args.angle):
        parser.error("dropout must be in [0,1) and angle finite")
    if not math.isfinite(args.j_exchange_scale) or not 0 < args.j_exchange_scale <= 1:
        parser.error("j-exchange-scale must be finite and in (0,1]")
    if not math.isfinite(args.gate_anchor) or not 0 <= args.gate_anchor <= 1:
        parser.error("gate-anchor must be finite and in [0,1]")
    if not math.isfinite(args.force_feature_scale) or args.force_feature_scale <= 0:
        parser.error("force-feature-scale must be positive and finite")
    if len(set(args.seeds)) != len(args.seeds):
        parser.error("seeds must be unique")
    return args


def main() -> None:
    args = _parse_args()
    if args.arm == "paired":
        for seed in args.seeds:
            _require_deferred_pair_files_ready(args, seed)
    torch.set_num_threads(args.threads)
    datasets, info = _load_data(args.data_root, args.coordinate_input,
                                args.layout,
                                include_test=(args.arm == "paired"),
                                force_feature_scale=args.force_feature_scale)
    print(json.dumps(info, sort_keys=True), flush=True)
    output_scale_stats = _output_scale_stats(args, datasets)
    if output_scale_stats is not None:
        print(json.dumps({"train_output_scale_stats": output_scale_stats},
                         sort_keys=True), flush=True)
    if args.check_only:
        _check_only(args, datasets, info, output_scale_stats)
        return
    device = torch.device(args.device)
    for seed in args.seeds:
        _run_seed(args, datasets, info, seed, device, output_scale_stats)


if __name__ == "__main__":
    main()
