"""Matched GCM runs on ICLR 2026 Plate Deformation static final-state prediction.

Input files are generated by ``scripts/prepare_plate_deformation.py`` from the
official Zenodo archive. Every graph uses t=0 as input and t=47 as the target,
with the fixed Sim000-799 / Sim800-899 / Sim900-999 split. The reported
``state_MSE`` is the official six-channel, original-unit, mask-restricted loss.

The two arms have identical parameters at initialization, graph compilation,
input information, optimizer, data order, and checkpoint selection. Only the
original-J exchange multiplier changes (0 versus 0.25 by default, or the
positive ``--j-exchange-scale`` value). Optional relay padding
uses empty butterfly wires as intra-block transport workspace; it does not
change the real-node output set or add a read mechanism.
``--balanced-carrier-heads K`` optionally initializes the existing J base
angle to pi/4 in the first K heads at every stage, with no new parameters.

The learned input follows the official environment's ``input_keys=[PROPERTIES]``:
six raw node properties and nine official edge features. The raw initial state
is used only as the residual offset. The default three-channel output predicts
the physical displacement once and reconstructs position and displacement;
``--independent-six-state`` retains an independent six-channel ablation. Both
freeze the known boundary/force-node state. The checkpoint metric matches the
paper's per-batch masked six-state loss, and node-weighted loss is also recorded.
``--output-scale train_std`` optionally multiplies the three-channel head by
the per-channel displacement-residual standard deviation from scored nodes in
the 800 training graphs before reconstructing the original-unit six-state.
``--arm j`` or ``--arm zero`` trains and selects one arm using train/validation
only. A later ``--arm paired --resume`` tests both validation-selected arms
once both validation-only records exist, then writes their paired comparison.
"""

